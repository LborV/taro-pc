def slope_point(s, depth=0.0):
    """Точка на наклонной части: s — расстояние по скату от линии перегиба,
    depth — вглубь от лицевой плоскости наклонной части. Возвращает (y, z)."""
    y = s * sin(TILT) + depth * cos(TILT)
    z = Z_TILT + s * cos(TILT) - depth * sin(TILT)
    return y, z


