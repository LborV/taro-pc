def band_point(u, depth=0.0):
    """Точка на нижнем поясе: u — вдоль пояса от низа, depth — вглубь. → (y, z)."""
    return (u * sin(BAND_TILT) + depth * cos(BAND_TILT),
            u * cos(BAND_TILT) - depth * sin(BAND_TILT))


def slope_point(s, depth=0.0):
    """Точка на грани экрана: s — по скату от линии перегиба, depth — вглубь. → (y, z)."""
    return (Y_TILT + s * sin(TILT) + depth * cos(TILT),
            Z_TILT + s * cos(TILT) - depth * sin(TILT))


